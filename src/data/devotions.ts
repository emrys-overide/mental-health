// Helper to get today's devotion based on day of year
export function getTodaysDevotion(): DailyDevotion {
  const now = new Date();
  // Generate day-of-year index
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = (now.getTime() - start.getTime()) + ((start.getTimezoneOffset() - now.getTimezoneOffset()) * 60 * 1000);
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);

  const index = Math.abs(dayOfYear) % DAILY_DEVOTIONS.length;
  const devotion = DAILY_DEVOTIONS[index];
  return {
    ...devotion,
    dateStr: now.toLocaleDateString(undefined, { weekday: 'long', month: 'short', day: 'numeric' })
  };
}
